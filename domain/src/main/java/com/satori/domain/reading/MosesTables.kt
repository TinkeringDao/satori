    /** Whether [cp] is in [table]. */
    fun contains(table: IntArray, cp: Int): Boolean {
        var low = 0
        var high = table.size / 2 - 1
        while (low <= high) {
            val mid = (low + high) ushr 1
            when {
                cp < table[2 * mid] -> high = mid - 1
                cp > table[2 * mid + 1] -> low = mid + 1
                else -> return true
            }
        }
        return false
    }
